# frozen_string_literal: true

# Generates Gemfile.floor: each customer-facing runtime dependency pinned to
# the LOWEST published version satisfying the gemspec constraint (its true
# floor), so CI can prove the declared floors are real and not aspirational.
# Bundler has no native lowest-version resolver, hence this generator. Dev/test
# tooling is copied verbatim from the main Gemfile and kept current. Everything
# is derived from the gemspec / Gemfile — nothing to keep in sync by hand.

require "rubygems"
require "rubygems/spec_fetcher"

spec = Gem::Specification.load(Dir["*.gemspec"].first)
fetcher = Gem::SpecFetcher.fetcher

File.open("Gemfile.floor", "w") do |f|
  f.puts %(source "https://rubygems.org")
  f.puts "# AUTO-GENERATED by scripts/floor_gemfile.rb — do not edit."
  spec.dependencies.select { |d| d.type == :runtime }.each do |d|
    tuples = fetcher.spec_for_dependency(d).first
    floor = tuples.map { |t, _| t.version }
                  .reject(&:prerelease?)
                  .select { |v| d.requirement.satisfied_by?(v) }
                  .min
    raise "no published version satisfies #{d.name} #{d.requirement}" unless floor
    f.puts %(gem "#{d.name}", "#{floor}")
  end
  dev_group = File.read("Gemfile")[/group :development.*?^end/m]
  f.write dev_group.lines[1..-2].join
end

puts File.read("Gemfile.floor")
